#!/usr/bin/env python3
"""Fail-closed mainnet approval gate.

A fresh paper-session log is necessary but not sufficient. A separate,
operator-reviewed evidence JSON must attest to drawdown, fees, data/ledger
integrity, out-of-sample coverage, Spot Testnet E2E, reconciliation and
kill-switch review. This script never changes TRADING_MODE or places orders.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.build_info import source_fingerprint  # noqa: E402
from app.history_windows import DEFAULT_EMBARGO_SECONDS  # noqa: E402
from app.live_approval import APPROVAL_VERSION, digest_json, is_digest  # noqa: E402
from app.live_execution_evidence import SpotEvidenceScope  # noqa: E402
from app.market_history import verify_capture_archive  # noqa: E402

load_dotenv()

MIN_PAPER_HOURS = 168.0
MIN_PAPER_TICKS = 1000
MIN_CLOSED_TRADES = 50
MAX_DRAWDOWN_PCT = 8.0
MAX_DAILY_FEES_USDT = 0.75
MIN_OOS_WINDOWS = 4
MIN_POSITIVE_OOS_WINDOWS = 3


def _number(data: dict, key: str, reasons: list[str]) -> float | None:
    value = data.get(key)
    try:
        if isinstance(value, bool):
            raise ValueError("boolean is not numeric evidence")
        result = float(value)
        if not math.isfinite(result):
            raise ValueError("not finite")
        return result
    except (TypeError, ValueError):
        reasons.append(f"evidence field {key!r} must be a finite number")
        return None


def check_oos(report: dict, *, profile: dict, fingerprint: str) -> tuple[int, int]:
    if (
        report.get("mode") != "rolling_walk_forward_research_only"
        or report.get("selection_policy") != "train_only_with_time_embargo_then_single_unseen_test_per_window"
        or report.get("source_fingerprint") != fingerprint
    ):
        raise ValueError("OOS report must be generated by the current build with the chronological embargo")
    if (
        report["starting_cash_per_asset_usdt"] != profile["starting_cash_usdt"]
        or report["order_size_usdt"] != profile["order_size_usdt"]
        or not profile["effective_fee_rate"] <= report["fee_rate"] < 0.1
    ):
        raise ValueError("OOS cash, order size or fee assumptions do not match the approved profile")
    asset = report["assets"][profile["symbol"]]
    expected_capture = asset.get("verified_capture_sha256")
    archive_path = asset.get("source")
    manifest_path = asset.get("verified_capture_manifest")
    if not is_digest(expected_capture) or not isinstance(archive_path, str) or not isinstance(manifest_path, str):
        raise ValueError("OOS report has no verifiable capture archive and manifest for the approved symbol")
    try:
        actual_capture = verify_capture_archive(archive_path, manifest_path, symbol=profile["symbol"])
    except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
        raise ValueError(f"OOS capture archive/manifest verification failed: {exc}") from exc
    if actual_capture != expected_capture:
        raise ValueError("OOS capture digest does not match the reverified archive")
    embargo = report["embargo_seconds"]
    if type(embargo) not in (int, float) or not math.isfinite(embargo) or embargo < DEFAULT_EMBARGO_SECONDS:
        raise ValueError(f"OOS embargo must be at least {DEFAULT_EMBARGO_SECONDS:.0f}s")
    windows = asset["windows"]
    if not isinstance(windows, list) or len(windows) != report["windows_requested"]:
        raise ValueError("OOS window count does not match the report")
    last = -1
    positive = 0
    for index, row in enumerate(windows, start=1):
        first, end, train = (row[k] for k in (
            "test_first_timestamp_ns", "test_last_timestamp_ns", "train_last_timestamp_ns",
        ))
        if (
            row.get("window") != index or any(type(t) is not int for t in (first, end, train))
            or not 0 <= train < first <= end or first <= last or first - train <= embargo * 1e9
        ):
            raise ValueError("OOS windows overlap or violate the chronological embargo")
        last = end
        m = row["unseen_test_metrics"]
        checks = (
            "closed_position_count", "final_open_quantity", "pending_orders_at_end",
            "invalid_depth_frames", "realized_pnl", "return_pct", "max_drawdown_pct",
        )
        if any(type(m[k]) not in (int, float) or not math.isfinite(m[k]) for k in checks):
            raise ValueError("OOS report contains malformed execution metrics")
        if m["invalid_depth_frames"] != 0:
            raise ValueError("OOS report contains invalid depth frames")
        if not 0 <= m["max_drawdown_pct"] < MAX_DRAWDOWN_PCT:
            raise ValueError("OOS report exceeds the drawdown threshold")
        if (
            row.get("no_trade_fallback") is False
            and m["closed_position_count"] > 0 and m["final_open_quantity"] == 0
            and m["pending_orders_at_end"] == 0 and m["realized_pnl"] > 0 and m["return_pct"] > 0
        ):
            positive += 1
    return len(windows), positive


def check_testnet_xml(payload: bytes) -> None:
    if len(payload) > 2_000_000:
        raise ValueError("Testnet result must be a bounded JUnit report with no document type")
    text = payload.decode("utf-8")
    if "<!DOCTYPE" in text.upper() or "<!ENTITY" in text.upper() or "\0" in text:
        raise ValueError("Testnet result must be a bounded JUnit report with no document type")
    root = ET.fromstring(text)
    cases = list(root.iter("testcase"))
    if (
        len(cases) != 1 or cases[0].get("classname") != "tests.test_spot_testnet_e2e"
        or cases[0].get("name") != "test_spot_testnet_market_oco_restart_cancel_and_exit"
    ):
        raise ValueError("Testnet report must contain exactly the signed Spot lifecycle test")
    suites = list(root.iter("testsuite"))
    if (
        root.tag not in {"testsuites", "testsuite"} or len(suites) != 1 or suites[0].get("tests") != "1"
        or any(suites[0].get(key, "0") != "0" for key in ("skipped", "failures", "errors"))
        or any(next(root.iter(tag), None) is not None for tag in ("skipped", "failure", "error"))
    ):
        raise ValueError("Signed Spot Testnet lifecycle did not pass")



def verify_testnet_attestation(path: Path, source_sha: str) -> None:
    """Verify the JUnit bytes against GitHub's signed provenance for this exact workflow."""
    if not re.fullmatch(r"[0-9a-f]{40}", source_sha):
        raise ValueError("Testnet source SHA must be a full 40-character lowercase commit SHA")
    gh = shutil.which("gh")
    if not gh:
        raise ValueError("GitHub CLI (gh) is required to verify the signed Testnet artifact provenance")
    command = [
        gh, "attestation", "verify", str(path),
        "--repo", "Nexora88/nexora-quant",
        "--signer-workflow",
        "Nexora88/nexora-quant/.github/workflows/spot-testnet-e2e.yml",
        "--source-ref", "refs/heads/main",
        "--source-digest", source_sha,
        "--deny-self-hosted-runners",
    ]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode:
        detail = (result.stderr or result.stdout or "no verifier output").strip()
        raise ValueError(f"GitHub Testnet artifact attestation verification failed: {detail[:1200]}")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--i-understand-real-money", action="store_true", required=True)
    p.add_argument("--overnight-log", type=Path, required=True)
    p.add_argument("--evidence-json", type=Path, required=True,
                   help="Operator-reviewed scorecard; see docs/GO_LIVE_CHECKLIST.md")
    p.add_argument("--live-profile", type=Path, required=True, help="Secret-free candidate profile JSON")
    p.add_argument("--mainnet-account-uid", type=int, required=True, help="Expected Binance account UID (not an API key)")
    p.add_argument("--oos-report", type=Path, required=True)
    p.add_argument("--testnet-junit", type=Path, required=True)
    p.add_argument("--testnet-source-sha", required=True,
                   help="Full commit SHA shown for the successful main-branch Testnet workflow run")
    p.add_argument("--stamp", type=Path, default=ROOT / "data" / "GO_LIVE_OK")
    args = p.parse_args()

    inputs = {
        "overnight": args.overnight_log, "scorecard": args.evidence_json,
        "oos": args.oos_report, "testnet": args.testnet_junit,
    }
    paths = [path.resolve() for path in (*inputs.values(), args.live_profile)]
    if len(set(paths)) != len(paths) or args.stamp.resolve() in paths:
        p.error("stamp and evidence inputs must be distinct files")
    args.stamp.unlink(missing_ok=True)

    reasons: list[str] = []
    if os.getenv("TRADING_MODE", "paper").strip().lower() != "paper":
        reasons.append("run the go-live gate while TRADING_MODE=paper")

    raw: dict[str, bytes] = {}
    for label, path in inputs.items():
        try:
            raw[label] = path.read_bytes()
        except OSError:
            reasons.append(f"{label} artifact unavailable: {path}")
    if "overnight" in raw:
        log_text = raw["overnight"].decode("utf-8", errors="replace")
        if log_text.strip().splitlines()[-1:] != ["OVERNIGHT_CHECK_PASS"]:
            reasons.append("overnight log missing OVERNIGHT_CHECK_PASS")
        match = re.search(r"INFO checked_at=([^\s]+)", log_text)
        if not match:
            reasons.append("overnight log missing checked_at timestamp")
        else:
            try:
                checked_at = datetime.fromisoformat(match.group(1).replace("Z", "+00:00"))
                if checked_at.tzinfo is None:
                    checked_at = checked_at.replace(tzinfo=timezone.utc)
                age = (datetime.now(timezone.utc) - checked_at).total_seconds()
                if age < -300 or age > 15 * 60:
                    reasons.append("overnight check log is stale or from the future; rerun it")
            except ValueError:
                reasons.append("overnight check timestamp is invalid")
        session = re.findall(r"^INFO session=\S+ duration=([\d.]+)h ticks=(\d+) reconnects=(\d+) ", log_text, re.M)
        trades_logged = re.findall(
            r"^INFO closed_trades=(\d+) fee_net_total=(\S+) fee_net_expectancy=(\S+) USDT/trade$",
            log_text, re.M,
        )
        try:
            if len(session) != 1 or len(trades_logged) != 1:
                raise ValueError("missing session and trade metrics")
            elapsed, ticks, reconnects = session[0]
            count, net, pnl_per_trade = trades_logged[0]
            if (
                float(elapsed) < MIN_PAPER_HOURS or int(ticks) < MIN_PAPER_TICKS or int(reconnects) != 0
                or int(count) < MIN_CLOSED_TRADES
                or not all(math.isfinite(float(n)) and float(n) > 0 for n in (net, pnl_per_trade))
            ):
                raise ValueError("session does not meet the paper duration, coverage or fee-net thresholds")
        except (ValueError, OverflowError) as exc:
            reasons.append(f"invalid overnight evidence: {exc}")

    evidence: dict = {}
    if "scorecard" in raw:
        try:
            evidence = json.loads(raw["scorecard"])
            if not isinstance(evidence, dict):
                raise ValueError("top-level JSON value must be an object")
        except (OSError, ValueError) as exc:
            reasons.append(f"operator evidence JSON unreadable: {exc}")
            evidence = {}

    hours = _number(evidence, "paper_hours", reasons)
    trades = _number(evidence, "closed_trades", reasons)
    expectancy = _number(evidence, "fee_net_expectancy_usdt", reasons)
    drawdown = _number(evidence, "max_drawdown_pct", reasons)
    daily_fees = _number(evidence, "max_daily_fees_usdt", reasons)
    oos_windows = _number(evidence, "oos_windows", reasons)
    positive_oos = _number(evidence, "positive_oos_windows", reasons)
    data_gaps = _number(evidence, "data_gaps", reasons)
    ledger_gaps = _number(evidence, "ledger_gaps", reasons)

    if hours is not None and hours < MIN_PAPER_HOURS:
        reasons.append(f"paper evidence is {hours:.1f}h; need at least {MIN_PAPER_HOURS:.0f}h")
    if trades is not None and trades < MIN_CLOSED_TRADES:
        reasons.append(f"only {trades:.0f} closed trades; need at least {MIN_CLOSED_TRADES}")
    if expectancy is not None and expectancy <= 0:
        reasons.append("fee-net expectancy must be positive")
    if drawdown is not None and not 0 <= drawdown < MAX_DRAWDOWN_PCT:
        reasons.append(f"max drawdown must be below {MAX_DRAWDOWN_PCT:.1f}%")
    if daily_fees is not None and not 0 <= daily_fees <= MAX_DAILY_FEES_USDT:
        reasons.append(f"daily fees must be <= {MAX_DAILY_FEES_USDT:.2f} USDT")
    if oos_windows is not None and oos_windows < MIN_OOS_WINDOWS:
        reasons.append(f"need at least {MIN_OOS_WINDOWS} chronological OOS windows")
    if positive_oos is not None and positive_oos < MIN_POSITIVE_OOS_WINDOWS:
        reasons.append(f"need at least {MIN_POSITIVE_OOS_WINDOWS} positive OOS windows")
    if data_gaps is not None and data_gaps != 0:
        reasons.append("paper evidence contains data gaps")
    if ledger_gaps is not None and ledger_gaps != 0:
        reasons.append("paper evidence contains ledger gaps")

    for key in ("testnet_e2e_pass", "exchange_reconciled", "kill_switch_reviewed"):
        if evidence.get(key) is not True:
            reasons.append(f"operator evidence {key}=true is required")

    fingerprint = source_fingerprint(ROOT)
    profile = {}
    symbol = ""
    try:
        profile = json.loads(args.live_profile.read_text(encoding="utf-8"))
        symbol = profile["symbol"]
        if (
            not isinstance(symbol, str) or not symbol.isascii() or not symbol.isalnum()
            or symbol != symbol.lower() or profile.get("trading_mode") != "live"
            or profile.get("binance_testnet") is not False or args.mainnet_account_uid <= 0
            or profile.get("prefer_maker") is not False
            or {"binance_api_key", "binance_api_secret", "jwt_secret", "live_confirm"} & profile.keys()
        ):
            raise ValueError("requires a secret-free Mainnet market-entry profile and a positive account UID")
        profile_hash = digest_json(profile)
    except (OSError, AttributeError, KeyError, TypeError, ValueError) as exc:
        reasons.append(f"invalid live profile: {exc}")

    if "oos" in raw and symbol:
        try:
            measured = check_oos(json.loads(raw["oos"]), profile=profile, fingerprint=fingerprint)
            if measured != (oos_windows, positive_oos):
                raise ValueError("scorecard window counts do not match the eligible OOS report windows")
        except (AttributeError, KeyError, TypeError, ValueError, OverflowError) as exc:
            reasons.append(f"invalid OOS evidence: {exc}")
    if "testnet" in raw:
        try:
            check_testnet_xml(raw["testnet"])
            verify_testnet_attestation(args.testnet_junit, args.testnet_source_sha)
        except (ValueError, ET.ParseError) as exc:
            reasons.append(f"invalid Testnet evidence: {exc}")

    if reasons:
        print("GO_LIVE_GATE_FAIL")
        for reason in reasons:
            print(f" - {reason}")
        return 1

    args.stamp.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "version": APPROVAL_VERSION,
        "ok": True,
        "ts": datetime.now(timezone.utc).isoformat(),
        "source_fingerprint": fingerprint,
        "profile_sha256": profile_hash,
        "account_binding": SpotEvidenceScope(args.mainnet_account_uid, False, symbol.upper()).stamp()["account_binding"],
        "testnet_source_sha": args.testnet_source_sha,
        "artifacts": {label: {
            "path": str(path.resolve()), "sha256": hashlib.sha256(raw[label]).hexdigest(),
        } for label, path in inputs.items()},
        "note": "Operator-attested evidence is required; this approval is not a profitability guarantee.",
    }
    with tempfile.NamedTemporaryFile(
        "w", dir=args.stamp.parent, encoding="utf-8", prefix=".go-live-", delete=False,
    ) as stream:
        temporary = Path(stream.name)
        try:
            json.dump(payload, stream, indent=2, allow_nan=False)
            stream.flush()
            os.fsync(stream.fileno())
            os.replace(temporary, args.stamp)
        finally:
            temporary.unlink(missing_ok=True)
    print("GO_LIVE_GATE_PASS")
    print(f"wrote {args.stamp}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
